class print
{
    public static void main(String[] args)
    {
        int a=5,b=10;
        System.out.println(a);// prints data with \n at the end
        System.out.print(a);// print() print values 
        System.out.print(b);
        System.out.println("\n The value at a is= "+a); // + used to concatinate to print lines
        System.out.print("The value at a is= "+a + "\n The value at b is= " + b);
        System.out.printf("\n The sum is = %d",a+b); 
    } 
}











